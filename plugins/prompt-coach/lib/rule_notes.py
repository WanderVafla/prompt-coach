"""Rule notes in the vault, and links to them that Obsidian resolves.

Reviews store only rule ids as `[[R4]]`. `finalize.py` turns each into a
Dataview inline query that renders a link labeled "R4 · <name>", the name
read from `_rules/R4.md`. Renaming a rule there renames it in every review.
"""

import re
from pathlib import Path

from lib import catalog

RULES_FOLDER = "_rules"
# A bare `[[R4]]`: inside an inline query it is always followed by `.file` or `.label`.
RULE_LINK = re.compile(r"\[\[([RT]\d)\]\](?!\.)")
MODE_ICON = {"learning": "🎓", "tool": "🛠️"}
HEADINGS = {
    "en": ("Good sign", "Bad sign", "Generated by prompt-coach: edits are overwritten on the next review."),
    "fr": ("Bon signe", "Mauvais signe", "Généré par prompt-coach : les modifications sont écrasées au prochain bilan."),
    "ru": ("Хорошо", "Плохо", "Создано prompt-coach: правки перезаписываются при следующем разборе."),
}


def inline_link(rule_id: str) -> str:
    return f"`=link([[{rule_id}]].file.path, [[{rule_id}]].label)`"


def resolve_links(note_text: str) -> str:
    """`[[R4]]` → Dataview inline link. Frontmatter is left alone."""
    head, sep, body = note_text.partition("\n---\n")
    if not sep:
        return RULE_LINK.sub(lambda m: inline_link(m.group(1)), note_text)
    return head + sep + RULE_LINK.sub(lambda m: inline_link(m.group(1)), body)


def write_all(reviews_folder: Path, language: str) -> Path:
    folder = reviews_folder / RULES_FOLDER
    folder.mkdir(exist_ok=True)
    good, bad, notice = HEADINGS.get(language, HEADINGS["en"])
    for rule_id, rule in catalog.rules().items():
        name = catalog.text(rule_id, "name", language)
        (folder / f"{rule_id}.md").write_text(
            f"---\nrule: {rule_id}\nmode: {rule['mode']}\nname: \"{name}\"\nlabel: \"{rule_id} · {name}\"\n---\n\n"
            f"# {MODE_ICON[rule['mode']]} {rule_id} · {name}\n\n"
            f"> [!success] {good}\n> {catalog.text(rule_id, 'good', language)}\n\n"
            f"> [!failure] {bad}\n> {catalog.text(rule_id, 'bad', language)}\n\n"
            f"*{notice}*\n",
            encoding="utf-8",
        )
    return folder
